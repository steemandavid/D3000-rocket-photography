#!/usr/bin/env python3
"""Generate the compile-time peer binding (spec §7.4): both MACs, PMK, LMK, channel.

Writes components/crig_common/include/crig_binding.h (git-ignored). Keys come from os.urandom.
Re-run (and re-flash BOTH units) when a board or chip is replaced.

    python3 tools/gen_binding.py --node 68:ee:8f:47:8e:c8 --remote 68:ee:8f:47:96:d4 [--channel 1]
"""
import argparse, os, sys
ap = argparse.ArgumentParser()
ap.add_argument('--node', required=True)
ap.add_argument('--remote', required=True)
ap.add_argument('--channel', type=int, default=1)
ap.add_argument('--force', action='store_true')
a = ap.parse_args()
if not 1 <= a.channel <= 13 or abs(a.channel - 11) < 5:
    sys.exit('channel must be 1..13 and >= 5 channels from the RLC channel 11 (spec RR-02)')
out = os.path.join(os.path.dirname(__file__), '..', 'components', 'crig_common', 'include', 'crig_binding.h')
if os.path.exists(out) and not a.force:
    sys.exit(f'{out} exists; use --force to regenerate keys (then re-flash both units)')
mac = lambda s: ', '.join('0x' + b for b in s.lower().split(':'))
key = lambda: ', '.join(f'0x{b:02x}' for b in os.urandom(16))
with open(out, 'w') as f:
    f.write('/* GENERATED by tools/gen_binding.py — secret, git-ignored, never commit (spec §7.4). */\n#pragma once\n')
    f.write(f'#define CRIG_NODE_MAC   {{ {mac(a.node)} }}\n#define CRIG_REMOTE_MAC {{ {mac(a.remote)} }}\n')
    f.write(f'#define CRIG_PMK        {{ {key()} }}\n#define CRIG_LMK        {{ {key()} }}\n#define CRIG_CHANNEL    {a.channel}\n')
print('wrote', os.path.normpath(out))
